#include <iostream>
using namespace std;

int main() {
	int n = 5;
	int m = 7;
	cout << "The product of " << n << " and " << m << " is ";
	cout << n * m << "." << endl;
	cout << "The sum of " << n << " and " << m << " is ";
	cout << n + m << "." << endl;
	cout << "The quotient of " << n << " and " << m << " is ";
	cout << n / m << "." << endl;
	cout << "The difference of " << m  << " and " << n << " is ";
	cout << m - n << "." << endl;
	
}
